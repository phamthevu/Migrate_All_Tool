def create_project_from_workbook(path, output_mcdm, project_name=None):
    check=inspect_workbook(path)
    if not check['valid']: raise ValueError('\n'.join(check['errors']))
    meta=check['meta']; pt=check['project_type']; name=project_name or meta.get('Project_Name') or Path(path).stem
    cfg,accounts=_build_config(path,pt,meta)
    ProjectDB.create_project(output_mcdm,name,pt,cfg,accounts)
    db=ProjectDB(output_mcdm)
    try:
        tmp = NamedTemporaryFile(prefix='researchstudio_normalized_', suffix='.xlsx', delete=False)
        legacy = Path(tmp.name)
        tmp.close()
        try:
            _copy_data_to_legacy(path,legacy,pt,cfg)
            result=import_file(db,str(legacy),autodetect=False)
            # mark imported source as original workbook rather than temp normalization file
            db.conn.execute("UPDATE responses SET source_file=?",(Path(path).name,)); db.conn.commit()
        finally:
            try: legacy.unlink(missing_ok=True)
            except OSError: pass
        return {'path':output_mcdm,'project_id':db.get_meta().get('project_id'),'storage_key':db.get_meta().get('storage_key'),'responses':result['responses'],'rows':result['rows'],'project_type':pt}
    except Exception:
        db.close()
        try: Path(output_mcdm).unlink(missing_ok=True)
        except Exception: pass
        raise
    finally:
        db.close()
