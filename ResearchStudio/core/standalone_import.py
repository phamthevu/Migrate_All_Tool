def _sheet_kv(wb, sheet):
    if sheet not in wb.sheetnames:return {}
    return {_s(r[0].value):_s(r[1].value) for r in wb[sheet].iter_rows(min_row=2) if len(r)>=2 and _s(r[0].value)}

def _metadata(wb):
    # V8.5: technical metadata is generated/hidden. Legacy V8.2 Metadata remains readable.
    sys=_sheet_kv(wb,'_System') or _sheet_kv(wb,'Metadata')
    setup=_sheet_kv(wb,'Project_Setup')
    if not sys: raise ValueError("This is not a Research Studio import template: missing hidden _System metadata. Use Download Import Template, or Scan / Detect Workbook to see what is missing.")
    return {
        'Project_Name':setup.get('Project Name') or sys.get('Project_Name') or 'Imported Historical Project',
        'Project_Type':sys.get('Project_Type',''),
        'Access_Mode':setup.get('Access Mode') or sys.get('Access_Mode') or 'Free',
        'Model_Type':sys.get('Model_Type',''),
        'Use_Z_Number':sys.get('Use_Z_Number','NO'),
    }

def detect_workbook(path):
    """Scan any Excel workbook and return a friendly type/schema diagnosis without importing it."""
    wb=load_workbook(path,data_only=True,read_only=True)
    sheets=list(wb.sheetnames); pt='UNKNOWN'; confidence='low'
    try:
        meta=_metadata(wb); pt=meta.get('Project_Type','').upper() or 'UNKNOWN'; confidence='template'
    except Exception:
        if any(str(s).startswith('Ans_') for s in sheets) or {'Factors_Alternatives','Lookup'} <= set(sheets): pt='MCDM'; confidence='structure'
        elif 'Questions' in sheets and 'Data' in sheets:
            hdr=[_s(x) for x in next(wb['Data'].iter_rows(values_only=True),[])];
            pt='QUALITATIVE_INTERVIEW' if {'Sequence','Question_ID','Answer'} <= set(hdr) else 'QUANTITATIVE_SURVEY'; confidence='structure'
    headers={}
    for sn in sheets[:20]:
        try: headers[sn]=[_s(x) for x in next(wb[sn].iter_rows(values_only=True),[])][:30]
        except Exception: headers[sn]=[]
    return {'project_type':pt,'confidence':confidence,'sheets':sheets,'headers':headers}


def _strict_schema_errors(path, wb, pt):
    """Validate that configuration sheets and data sheets agree with each other."""
    errors=[]
    try:
        if pt=='QUANTITATIVE_SURVEY':
            questions,_=parse_survey_excel(path)
            qids=[str(q.question_id) for q in questions if str(q.question_type) not in {'TITLE','SECTION','DESCRIPTION'}]
            if not qids: errors.append('Questions sheet contains no usable quantitative questions.')
            expected_data=[]
            for q in questions:
                qt=str(q.question_type).upper()
                opts=_s(q.options)
                if qt in {'SINGLE_CHOICE','MULTI_CHOICE','LIKERT','MATRIX_LIKERT'} and not opts:
                    errors.append(f"{q.question_id}: {qt} requires Options / Choices.")
                if qt.startswith('MATRIX_'):
                    if not q.matrix_items: errors.append(f'{q.question_id}: matrix question requires Matrix_Items.')
                    expected_data.extend([str(x.get('item_id')) for x in q.matrix_items if x.get('item_id')])
                elif qt not in {'TITLE','SECTION','DESCRIPTION'}:
                    expected_data.append(str(q.question_id))
            if 'Data' in wb.sheetnames:
                rows=list(wb['Data'].iter_rows(values_only=True,max_row=2))
                headers=[_s(x) for x in (rows[0] if rows else [])]
                if len(headers)!=len(set(headers)): errors.append('Data sheet has duplicate column headers.')
                base=['Answer_ID','Respondent_ID','Participant_Name','Username','Organization','Submitted_At','Modified_At']
                expected=base+expected_data
                missing=[x for x in expected if x not in headers]
                extra=[x for x in headers if x and x not in expected]
                if missing: errors.append('Data sheet is missing configured column(s): '+', '.join(missing))
                if extra: errors.append('Data sheet contains column(s) not defined by the schema: '+', '.join(extra))
                if headers and headers!=expected:
                    errors.append('Data headers/order do not match Questions + Matrix_Items schema.')
        elif pt=='QUALITATIVE_INTERVIEW':
            questions,_=parse_qualitative_excel(path)
            valid={str(q.get('question_id')) for q in questions}
            if 'Data' in wb.sheetnames:
                rows=list(wb['Data'].iter_rows(values_only=True))
                headers=[_s(x) for x in (rows[0] if rows else [])]
                expected=['Interview_ID','Respondent_ID','Participant_Name','Username','Organization','Submitted_At','Modified_At','Sequence','Type','Question_ID','Question','Answer']
                missing=[x for x in expected if x not in headers]
                extra=[x for x in headers if x and x not in expected]
                if missing: errors.append('Data sheet is missing required qualitative column(s): '+', '.join(missing))
                if extra: errors.append('Data sheet contains unexpected qualitative column(s): '+', '.join(extra))
                if headers and headers!=expected: errors.append('Qualitative Data headers/order do not match the required schema.')
                if not missing:
                    hi={x:i for i,x in enumerate(headers)}
                    for n,row in enumerate(rows[1:],2):
                        if not any(_s(x) for x in row): continue
                        typ=_s(row[hi['Type']] if hi['Type']<len(row) else '').upper()
                        qid=_s(row[hi['Question_ID']] if hi['Question_ID']<len(row) else '')
                        if typ not in {'INITIAL','FOLLOW_UP'}: errors.append(f'Data row {n}: Type must be INITIAL or FOLLOW_UP.')
                        if typ=='INITIAL' and qid not in valid: errors.append(f'Data row {n}: Question_ID {qid!r} is not defined in Questions.')
        elif pt=='MCDM':
            meta=_metadata(wb)
            cfg,_=_build_config(path,pt,meta)
            factors=[x for x in cfg.get('factors',[]) if str(x.get('type','Factor')).lower()!='alternative']
            alts=cfg.get('alternatives',[])
            model=str(cfg.get('model_type') or cfg.get('model') or '').upper()
            expected_rows=[_s(x.get('code')) for x in (alts if model=='TOPSIS' else factors)]
            expected_cols=['Rating'] if model=='DELPHI' else [_s(x.get('code')) for x in factors]
            z=bool(cfg.get('use_z_number'))
            acodes={_s(x.get('code')) for x in (cfg.get('z_scales_a',[]) if z else cfg.get('standard_scales',[]))}
            bcodes={_s(x.get('code')) for x in cfg.get('z_scales_b',[])}
            for sn in [x for x in wb.sheetnames if str(x).startswith('Ans_')]:
                rows=list(wb[sn].iter_rows(values_only=True))
                headers=[_s(x) for x in (rows[0] if rows else [])]
                actual_cols=headers[1:]
                actual_rows=[_s(r[0]) for r in rows[1:] if r and _s(r[0])]
                if actual_cols!=expected_cols: errors.append(f'{sn}: matrix columns do not match the configured model/factors.')
                if actual_rows!=expected_rows: errors.append(f'{sn}: matrix rows do not match the configured model/factors/alternatives.')
                for ri,row in enumerate(rows[1:],2):
                    for ci,cell in enumerate(row[1:],2):
                        value=_s(cell)
                        if not value: continue
                        a,b=(value.split('|',1)+[''])[:2] if '|' in value else (value,'')
                        if a not in acodes: errors.append(f'{sn}!R{ri}C{ci}: unknown assessment code {a!r}.')
                        if z and b not in bcodes: errors.append(f'{sn}!R{ri}C{ci}: unknown Z reliability code {b!r}.')
                        if not z and b: errors.append(f'{sn}!R{ri}C{ci}: Z-number value found while Z-number is OFF.')
    except Exception as exc:
        errors.append('Schema/configuration is invalid: '+str(exc))
    return errors

def inspect_workbook(path):
    wb=load_workbook(path,data_only=True,read_only=True); errors=[]
    try: meta=_metadata(wb)
    except Exception as e:
        scan=detect_workbook(path); meta={'Project_Type':scan['project_type']}; errors.append(str(e))
    pt=meta.get('Project_Type','').upper()
    if pt not in {'MCDM','QUANTITATIVE_SURVEY','QUALITATIVE_INTERVIEW'}: errors.append('Could not determine a supported project type. Download the matching Research Studio template and copy/map your data into it.')
    required={'MCDM':['Factors_Alternatives','Experts','Lookup'],'QUANTITATIVE_SURVEY':['Questions','Data'],'QUALITATIVE_INTERVIEW':['Questions','Data']}.get(pt,[])
    for sn in required:
        if sn not in wb.sheetnames: errors.append(f"Missing required sheet '{sn}'.")
    # Accounts are optional in Free/Anonymous Quant/Qual; mandatory only when Account mode is selected.
    if pt in {'QUANTITATIVE_SURVEY','QUALITATIVE_INTERVIEW'} and _s(meta.get('Access_Mode')).lower()=='account':
        if 'Accounts' not in wb.sheetnames:
            errors.append("Access Mode = Account requires the 'Accounts' sheet.")
        else:
            rows=list(wb['Accounts'].iter_rows(values_only=True,max_row=3))
            if len(rows)<2 or not any(_s(v) for v in rows[1]): errors.append("Access Mode = Account requires at least one account row in 'Accounts'.")
    if pt=='MCDM' and 'Experts' in wb.sheetnames:
        rows=list(wb['Experts'].iter_rows(values_only=True,max_row=3))
        if len(rows)<2 or not any(_s(v) for v in rows[1]): errors.append("MCDM requires at least one expert row in 'Experts'.")
    if pt=='MCDM' and not any(str(sn).startswith('Ans_') for sn in wb.sheetnames): errors.append('MCDM import requires at least one Ans_XX matrix sheet.')
    if pt=='MCDM' and 'Lookup' in wb.sheetnames:
        lookup_rows=list(wb['Lookup'].iter_rows(values_only=True))
        lookup_ids=set()
        if lookup_rows:
            lh=[_s(x) for x in lookup_rows[0]]
            for row in lookup_rows[1:]:
                d=dict(zip(lh,row)); aid=_s(d.get('Answer_ID'))
                if aid: lookup_ids.add(aid)
        ans_sheets=[str(sn) for sn in wb.sheetnames if str(sn).startswith('Ans_')]
        missing=[sn for sn in ans_sheets if sn not in lookup_ids]
        if missing:
            errors.append("Every Ans_XX sheet must have a matching Lookup row. Missing: "+", ".join(missing))
    preview=[]; headers=[]; sheet=''
    if pt in {'QUANTITATIVE_SURVEY','QUALITATIVE_INTERVIEW'} and 'Data' in wb.sheetnames:
        sheet='Data'; rows=list(wb['Data'].iter_rows(values_only=True,max_row=51)); headers=[_s(x) for x in (rows[0] if rows else [])]; preview=[dict(zip(headers,r)) for r in rows[1:]]
    elif pt=='MCDM':
        sheets=[sn for sn in wb.sheetnames if str(sn).startswith('Ans_')]
        if sheets:
            sheet=sheets[0]; rows=list(wb[sheet].iter_rows(values_only=True,max_row=20)); headers=[_s(x) for x in (rows[0] if rows else [])]; preview=[{'Row':_s(r[0]),**{headers[i]:r[i] for i in range(1,min(len(r),len(headers)))}} for r in rows[1:]]; headers=['Row']+headers[1:]
    if pt in {'MCDM','QUANTITATIVE_SURVEY','QUALITATIVE_INTERVIEW'}:
        errors.extend(_strict_schema_errors(path,wb,pt))
    # keep messages readable and deterministic
    errors=list(dict.fromkeys(errors))
    result={'valid':not errors,'errors':errors,'meta':meta,'project_type':pt,'sheet':sheet,'headers':headers,'preview':preview,'sheets':list(wb.sheetnames),'scan':detect_workbook(path)}
    wb.close()
    return result

def _accounts_from_sheet(wb, name='Accounts'):
    if name not in wb.sheetnames:return []
    rows=list(wb[name].iter_rows(values_only=True));
    if not rows:return []
    h=[_s(x) for x in rows[0]]; out=[]
    for row in rows[1:]:
        d=dict(zip(h,row)); rid=_s(d.get('Respondent_ID')); user=_s(d.get('Username'))
        if not rid and not user:continue
        out.append({'Respondent_ID':rid,'Username':user or rid,'Password':_s(d.get('Password')) or '123','Full_Name':_s(d.get('Full_Name') or d.get('Expert_Name')),'Organization':_s(d.get('Organization'))})
    return out

