def _finish(wb,path):
    # START_HERE must be the first visible tab.
    if 'START_HERE' in wb.sheetnames:
        wb._sheets.insert(0, wb._sheets.pop(wb._sheets.index(wb['START_HERE'])))
    for ws in wb.worksheets:
        ws.freeze_panes='A2'
        for col in ws.columns:
            try: ws.column_dimensions[col[0].column_letter].width=min(max(12,max(len(str(c.value or '')) for c in col)+2),45)
            except Exception: pass
    Path(path).parent.mkdir(parents=True,exist_ok=True); wb.save(path); return str(path)

